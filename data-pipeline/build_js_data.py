import json

with open("unified_chemical_products.json", "r", encoding="utf-8") as f:
    products = json.load(f)

# Also let's extract distinct categories
categories = set()
for p in products:
    for c in p.get("categories", []):
        categories.add(c)

categories_list = [
    "All Divisions",
    "Chlorination Process",
    "Nitration Process",
    "Hydrogenation Process",
    "Acid Chlorides",
    "Chlor-Alkali & Electrolysis",
    "Sulphonation Process",
    "Ethoxylation Process",
    "Ammonolysis Process",
    "Methoxylation Process",
    "Oxidation & Neutralization",
    "Sulphuric & Bulk Chemical Division",
    "Textile & Denim Processing"
]

js_content = f"""/**
 * Bhagwati Chemicals x KCIL Sister Enterprise Chemical Master Catalog
 * Full technical database: 85 chemical products across 11 manufacturing processes
 * Autogenerated & curated from official specifications
 */

const CHEMICAL_CATEGORIES = {json.dumps(categories_list, indent=2)};

const CHEMICAL_PRODUCTS = {json.dumps(products, indent=2)};

if (typeof module !== 'undefined' && module.exports) {{
  module.exports = {{ CHEMICAL_PRODUCTS, CHEMICAL_CATEGORIES }};
}}
"""

with open("assets/js/products-data.js", "w", encoding="utf-8") as f:
    f.write(js_content)

print("Generated assets/js/products-data.js successfully!")
